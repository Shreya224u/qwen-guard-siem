from typing import Optional

from sqlalchemy import (
    Column,
    Integer,
    String,
    Float,
    DateTime,
    Text,
    ForeignKey,
)
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func

from app.db.base import Base


class Alert(Base):
    """
    Alert generated by the Rule Engine or ML Engine.

    Lifecycle:
        NEW
        -> UNDER_INVESTIGATION
        -> CONFIRMED_THREAT / FALSE_POSITIVE
        -> RESOLVED
    """

    __tablename__ = "alerts"

    # ---------------------------------------------------------
    # Primary Key
    # ---------------------------------------------------------

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    # ---------------------------------------------------------
    # Original Log Reference
    # ---------------------------------------------------------

    log_id = Column(
        Integer,
        ForeignKey("log_entries.id"),
        nullable=False,
        index=True,
    )

    # ---------------------------------------------------------
    # Detection Information
    # ---------------------------------------------------------

    alert_type = Column(
        String(100),
        nullable=False,
        index=True,
    )

    rule_name = Column(
        String(255),
        nullable=False,
    )

    severity = Column(
        String(50),
        nullable=False,
        index=True,
    )

    # ---------------------------------------------------------
    # Detection Scores
    # ---------------------------------------------------------

    risk_score = Column(
        Float,
        nullable=False,
        default=0.0,
    )

    confidence = Column(
        Float,
        nullable=False,
        default=0.5,
    )

    # ---------------------------------------------------------
    # Source Information
    # ---------------------------------------------------------

    ip_address = Column(
        String(100),
        nullable=True,
        index=True,
    )

    description = Column(
        Text,
        nullable=True,
    )

    # ---------------------------------------------------------
    # Alert Lifecycle
    # ---------------------------------------------------------

    status = Column(
        String(50),
        nullable=False,
        default="NEW",
        index=True,
    )

    # ---------------------------------------------------------
    # Investigation Information
    # ---------------------------------------------------------

    confidence_score = Column(
        Float,
        nullable=True,
    )

    investigation_result = Column(
        String(100),
        nullable=True,
    )

    investigation_reason = Column(
        Text,
        nullable=True,
    )

    detected_by = Column(
        String(100),
        nullable=True,
    )

    related_event_count = Column(
        Integer,
        nullable=True,
        default=0,
    )

    recommended_action = Column(
        String(255),
        nullable=True,
    )

    investigated_by = Column(
        String(100),
        nullable=True,
    )

    investigated_at = Column(
        DateTime(timezone=True),
        nullable=True,
    )

    resolved_at = Column(
        DateTime(timezone=True),
        nullable=True,
    )

    # ---------------------------------------------------------
    # MITRE ATT&CK Mapping
    # ---------------------------------------------------------

    mitre_technique_fk = Column(
        Integer,
        ForeignKey("mitre_techniques.id"),
        nullable=True,
        index=True,
    )

    mitre_technique = relationship(
        "MitreTechnique",
        lazy="joined",
    )

    @property
    def mitre_technique_id(self) -> Optional[str]:
        return (
            self.mitre_technique.technique_id
            if self.mitre_technique
            else None
        )

    @property
    def mitre_technique_name(self) -> Optional[str]:
        return (
            self.mitre_technique.name
            if self.mitre_technique
            else None
        )

    @property
    def mitre_tactic(self) -> Optional[str]:
        return (
            self.mitre_technique.tactic
            if self.mitre_technique
            else None
        )

    # ---------------------------------------------------------
    # Timestamp
    # ---------------------------------------------------------

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )